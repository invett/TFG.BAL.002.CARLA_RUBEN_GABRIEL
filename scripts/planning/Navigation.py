import carla
import math
import sys
import random

# Adjust path to CARLA installation if not in PYTHONPATH
sys.path.append('/home/ruben/CARLA_0.9.14/PythonAPI/carla') 
from agents.navigation.global_route_planner import GlobalRoutePlanner

# Custom Modules
from penalty_manager import RoutePenaltyManager
from replanning_manager import ReplanningManager

class RouteManager:
    """
    Manages the lifecycle of the vehicle's path, including generation,
    monitoring, and dynamic recalculation based on semantic obstacles.
    """

    def __init__(self, world, sampling_resolution=2.0):
        """
        Initializes the RouteManager and its sub-components.

        Args:
            world (carla.World): The simulation world object.
            sampling_resolution (float): Distance (in meters) between waypoints 
                                         generated by the GlobalRoutePlanner.
        """
        self.world = world
        self.map = world.get_map()
        
        # 1. Initialize Global Route Planner (Standard CARLA API)
        self.grp = GlobalRoutePlanner(self.map, sampling_resolution)
        
        # 2. Initialize Penalty and Replanning Managers
        # Note: We access _graph (protected member) because RoutePenaltyManager 
        # needs direct access to the NetworkX graph to update edge weights.
        self.penalty_manager = RoutePenaltyManager(self.grp._graph)
        self.replanner = ReplanningManager(self.map)
        
        # State variables
        self.current_route = []
        self.destination_transform = None

    def generate_initial_route(self, start_transform, destination_transform=None):
        """
        Generates a route from the start position to a destination.
        
        If no destination is provided, it selects a random spawn point that 
        ensures a sufficiently long route.

        Args:
            start_transform (carla.Transform): The starting position of the vehicle.
            destination_transform (carla.Transform, optional): The target destination. 
                                                               Defaults to None.

        Returns:
            tuple:
                - list (current_route): List of (waypoint, road_option) tuples.
                - carla.Transform (destination_transform): The final destination.
        """
        if destination_transform is None:
            spawn_points = self.map.get_spawn_points()
            
            # Search for a distant point to ensure a decent drive length
            for _ in range(20):
                candidate = random.choice(spawn_points)
                route = self.grp.trace_route(start_transform.location, candidate.location)
                if len(route) > 100: # Ensure route is long enough
                    self.destination_transform = candidate
                    self.current_route = route
                    return route, self.destination_transform
            
            # Fallback if no long route is found
            self.destination_transform = spawn_points[-1]
        else:
            self.destination_transform = destination_transform

        self.current_route = self.grp.trace_route(start_transform.location, self.destination_transform.location)
        return self.current_route, self.destination_transform

    def check_and_replan(self, ego_transform, perception_event):
        """
        Evaluates a perception event to determine if the route is blocked and 
        triggers a recalculation if necessary.

        This method coordinates the ReplanningManager (to identify the blocked topology)
        and the PenaltyManager (to update the pathfinding graph cost).

        Args:
            ego_transform (carla.Transform): Current vehicle transform.
            perception_event (object): Data structure containing obstacle details 
                                       from the neural network/perception layer.

        Returns:
            tuple:
                - bool: True if replanning occurred, False otherwise.
                - list: The new (or current) route list.
        """
        # 1. Process event to find specific map coordinates (waypoints) that are blocked
        blocked_waypoints = self.replanner.process_nn_event(ego_transform, perception_event, self.world)
        
        if not blocked_waypoints:
            return False, self.current_route

        print(f"⚠️ BLOCKAGE DETECTED: Penalizing {len(blocked_waypoints)} nodes in the topology graph.")

        # 2. Apply penalty to the graph edges corresponding to the blocked waypoints
        self.penalty_manager.apply_penalty_near_waypoints(
            blocked_waypoints,
            penalty_value=5000.0, # High cost to force A* to find an alternative
            radius=4.0
        )

        # 3. Recalculate route using the updated graph weights
        print("🔄 Recalculating route...")
        
        # It is critical to replan from the current ego location, not the original start
        new_route = self.grp.trace_route(ego_transform.location, self.destination_transform.location)
        
        # Update state
        self.current_route = new_route
        return True, new_route

    def get_steering_angle(self, vehicle, curr_wp_idx):
        """
        Calculates the steering angle required to follow the current route using 
        a Lookahead/Pure Pursuit logic.

        Args:
            vehicle (carla.Vehicle): The ego vehicle object.
            curr_wp_idx (int): The index of the nearest waypoint in the route list.

        Returns:
            float: Steering angle in degrees [-180, 180].
        """
        if curr_wp_idx >= len(self.current_route) - 1:
            return 0.0

        next_angles = []
        lookahead_steps = 10
        step_jump = 3
        
        # Collect angles for a few points ahead to smooth the decision
        for i in range(lookahead_steps):
            idx = curr_wp_idx + i * step_jump
            if idx < len(self.current_route) - 1:
                wp = self.current_route[idx][0]
                angle = self._calculate_angle(vehicle, wp)
                next_angles.append(angle)
        
        # Select the first valid angle that isn't too sharp (filtering outliers)
        valid_idx = 0
        while valid_idx < len(next_angles) - 2 and abs(next_angles[valid_idx]) > 40:
            valid_idx += 1
            
        return next_angles[valid_idx] if next_angles else 0.0

    def _calculate_angle(self, vehicle, wp):
        """
        Helper method to compute the geometric angle between the vehicle's 
        forward vector and the target waypoint.

        Args:
            vehicle (carla.Vehicle): The ego vehicle.
            wp (carla.Waypoint): The target waypoint.

        Returns:
            float: Angle difference in degrees.
        """
        vehicle_pos = vehicle.get_transform()
        v_loc = vehicle_pos.location
        w_loc = wp.transform.location
        
        x_diff = w_loc.x - v_loc.x
        y_diff = w_loc.y - v_loc.y
        
        car_vector = vehicle_pos.get_forward_vector()
        target_rad = math.atan2(y_diff, x_diff)
        car_rad = math.atan2(car_vector.y, car_vector.x)
        
        degrees = math.degrees(target_rad - car_rad)
        
        # Normalize to [-180, 180]
        if degrees < -180: degrees += 360
        elif degrees > 180: degrees -= 360
        
        return degrees

    def is_end_of_route(self, curr_wp_idx):
        """
        Checks if the vehicle has reached the end of the route.

        Args:
            curr_wp_idx (int): Current waypoint index.

        Returns:
            bool: True if close to the end, False otherwise.
        """
        return curr_wp_idx >= len(self.current_route) - 5