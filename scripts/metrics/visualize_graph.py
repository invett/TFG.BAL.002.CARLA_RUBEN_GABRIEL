"""
--------------------------------------------------------------------------
Topological Graph Visualizer
--------------------------------------------------------------------------
Description:
    Standalone script to render the navigation graph.
    Extracts the topological network generated by the `RouteManager` (based on NetworkX)
    and implements spatial filtering to visually map and export
    a 2D representation of all CARLA road nodes and edges.

Usage:
    python visualize_graph.py [--host HOST] [--port PORT]

Dependencies:
    - carla (0.9.x)
    - argparse
    - sys
    - matplotlib
    - networkx
    - Navigation (custom)
--------------------------------------------------------------------------
"""

import carla
import argparse
import sys
import matplotlib.pyplot as plt
import networkx as nx

try:
    from Navigation import RouteManager
except ImportError:
    print("❌ Error: Module 'Navigation.py' not found.")
    sys.exit(1)

def plot_navigation_graph(graph, output_file="grafo_topologico.png"):
    """
    Draws and exports the navigation graph to an image using the 
    real spatial (x, y) coordinates of its nodes in CARLA.

    Args:
        graph (networkx.DiGraph): Directed graph representing the topological map.
        output_file (str, optional): Name of the output PNG file. Defaults to "grafo_topologico.png".
    """
    plt.figure(figsize=(12, 12))
    
    # Extract the (x, y) positions of the nodes.
    # networkx allows using a {node: (x, y)} dictionary to position them.
    posiciones = {}
    for nodo, data in graph.nodes(data=True):
        vertex = data.get('vertex')
        if vertex:
            posiciones[nodo] = (vertex[0], vertex[1]) # Ignore Z for the 2D view
            
    # Draw the nodes
    nx.draw_networkx_nodes(graph, posiciones, node_size=15, node_color='blue', alpha=0.6)
    
    # Draw the edges
    nx.draw_networkx_edges(graph, posiciones, arrowstyle='->', arrowsize=10, edge_color='gray', alpha=0.5)
    
    plt.title("Spatial Representation of the Navigation Graph", fontsize=16)
    plt.xlabel("X Coordinate (m)")
    plt.ylabel("Y Coordinate (m)")
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.axis('equal') # Maintain spatial proportion
    
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    print(f"Graph successfully exported to {output_file}")

def main():
    """
    Main execution function.
    1. Processes network arguments (Host/Port).
    2. Connects to the CARLA simulator.
    3. Initializes the `RouteManager` to extract the graph.
    4. Triggers the rendering and exporting of the graph.
    """
    parser = argparse.ArgumentParser()
    parser.add_argument('--host', default='127.0.0.1')
    parser.add_argument('--port', default=2000, type=int)
    args = parser.parse_args()

    try:
        client = carla.Client(args.host, args.port)
        client.set_timeout(10.0)
        world = client.get_world()
        
        route_manager = RouteManager(world)
        grafo_red = route_manager.grp._graph

        plot_navigation_graph(grafo_red)

    except Exception as e:
        print(f"❌ Error: {e}")

if __name__ == '__main__':
    main()