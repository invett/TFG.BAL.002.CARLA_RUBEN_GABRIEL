"""
--------------------------------------------------------------------------
Junction Topology Visualizer
--------------------------------------------------------------------------
Description:
    Debugging and spatial visualization tool for junctions in the 
    CARLA simulator. The script finds the nearest junction, extracts its 
    logical connections (Entry -> Exit), and draws them in the 3D world 
    along with the interpolated route from the GlobalRoutePlanner. Useful 
    for validating penalty points in topology management.

Usage:
    python draw_junction.py

Dependencies:
    - carla (0.9.x)
    - random
    - sys
    - agents.navigation.global_route_planner
--------------------------------------------------------------------------
"""

import carla
import random
import sys

sys.path.append('C:/Users/axanz/Desktop/CARLA_0.9.15/WindowsNoEditor/PythonAPI/carla')
from agents.navigation.global_route_planner import GlobalRoutePlanner

def main():
    """
    Main function.
    1. Connects to the CARLA simulator.
    2. Moves forward through waypoints from a spawn point until a junction is detected.
    3. Extracts and illustrates the raw topology (logical lane connections).
    4. Selects a random route within the junction and demonstrates the intermediate
       points that CARLA's global router traces over it.
    """
    # 1. Connect to the simulator
    client = carla.Client('localhost', 2000)
    client.set_timeout(10.0)
    world = client.get_world()
    carla_map = world.get_map()
    debug = world.debug

    # 2. Find a junction on the map
    spawn_points = carla_map.get_spawn_points()
    start_wp = carla_map.get_waypoint(spawn_points[0].location)

    # Move forward along the lane until a junction is found
    while not start_wp.is_junction:
        # Move forward 2 meters at a time
        next_wps = start_wp.next(2.0)
        if not next_wps:
            break
        start_wp = next_wps[0]

    if not start_wp.is_junction:
        print("No nearby junction found. Try a different map.")
        return

    junction = start_wp.get_junction()
    print(f"Inspecting Junction ID: {junction.id}")

    # 3. Visualize Junction Topology (Without intermediate points)
    # get_waypoints returns a list of tuples (entry, exit) for all lanes
    connection_waypoints = junction.get_waypoints(carla.LaneType.Driving)

    print(f"Drawing {len(connection_waypoints)} logical connections (Entry -> Exit)...")
    for entry_wp, exit_wp in connection_waypoints:
        # Draw entry point (Green)
        debug.draw_point(entry_wp.transform.location, size=0.15, color=carla.Color(0, 255, 0), life_time=30.0)
        # Draw exit point (Red)
        debug.draw_point(exit_wp.transform.location, size=0.15, color=carla.Color(255, 0, 0), life_time=30.0)
        
        # Draw straight line to show the absence of intermediate points in the topology
        debug.draw_line(entry_wp.transform.location, exit_wp.transform.location, thickness=0.05, color=carla.Color(255, 255, 0), life_time=30.0)

    # 4. Demonstrate GlobalRoutePlanner (With intermediate points)
    # Pick a random connection to trace the route
    test_entry, test_exit = random.choice(connection_waypoints)

    # Initialize the planner with a 1.0 meter resolution
    sampling_resolution = 1.0
    grp = GlobalRoutePlanner(carla_map, sampling_resolution)

    # Trace the route from entry to exit
    route = grp.trace_route(test_entry.transform.location, test_exit.transform.location)
    
    print(f"The GlobalRoutePlanner generated {len(route)} waypoints to connect this entry and exit.")

    # Draw intermediate points generated by GlobalRoutePlanner (Blue)
    for waypoint, road_option in route:
        loc = waypoint.transform.location
        # Raise the point slightly on the Z axis (0.5m) to make it visible above the asphalt and lines
        loc.z += 0.5 
        debug.draw_point(loc, size=0.1, color=carla.Color(0, 0, 255), life_time=30.0)

if __name__ == '__main__':
    main()